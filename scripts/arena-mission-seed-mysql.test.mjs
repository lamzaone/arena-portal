import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { readFile } from 'node:fs/promises';
import test from 'node:test';
import mysql from 'mysql2/promise';
import { seedArenaMissionLibrary } from './seed-arena-missions.mjs';
import { validateMissionPool } from './arena-mission-seed-policy.mjs';

const databaseUrl = process.env.TAPPED_MISSION_SEED_TEST_DB;
test('MariaDB seed audit, apply, repeat, staff preservation and backup failure use a disposable database', { skip: !databaseUrl }, async () => {
    const endpoint = new URL(databaseUrl);
    assert.ok(['127.0.0.1', 'localhost', '[::1]'].includes(endpoint.hostname), 'Seed acceptance tests require an explicit loopback test database.');
    const database = 'arena_mission_seed_test_' + randomUUID().replaceAll('-', '');
    assert.match(database, /^arena_mission_seed_test_[a-f0-9]{32}$/);
    const connection = await mysql.createConnection({ uri: databaseUrl, connectTimeout: 10000, timezone: 'Z', dateStrings: true, supportBigNumbers: true, bigNumberStrings: true });
    let created = false;
    try {
        await connection.query('CREATE DATABASE `' + database + '`');
        created = true;
        await connection.query('USE `' + database + '`');
        await connection.query("SET SESSION time_zone = '+00:00'");
        const source = await readFile(new URL('../db/046_mission_definitions.sql', import.meta.url), 'utf8');
        for (const statement of source.replace(/^\s*--[^\n]*$/gm, '').split(';').map(value => value.trim()).filter(Boolean))
            await connection.query(statement);
        const missions = validateMissionPool(JSON.parse(await readFile(new URL('../lib/missions/arena-mission-pool.json', import.meta.url), 'utf8')));
        const backups = new Map();
        const writeBackup = async (name, data) => { backups.set(name, structuredClone(data)); };
        const now = new Date('2026-10-22T10:00:00Z');
        const run = extra => seedArenaMissionLibrary({ connection, missions, writeBackup, now, ...extra });
        const counts = async () => {
            const [[parents]] = await connection.query('SELECT COUNT(*) AS n FROM portal_mission_definitions');
            const [[versions]] = await connection.query('SELECT COUNT(*) AS n FROM portal_mission_definition_versions');
            return [Number(parents.n), Number(versions.n)];
        };
        assert.deepEqual(await run(), { mode: 'audit', planned: 100, preserved: 0, inserted: 0, verified: true });
        assert.deepEqual(await counts(), [0, 0]);
        assert.equal(backups.get('before.json').plan.insertions.length, 100);
        assert.equal((await run({ apply: true })).inserted, 100);
        assert.deepEqual(await counts(), [100, 100]);
        const [boundaries] = await connection.query('SELECT period_kind,MIN(effective_period_start) AS start FROM portal_mission_definition_versions GROUP BY period_kind ORDER BY period_kind');
        assert.deepEqual(boundaries.map(row => [row.period_kind, row.start]), [['daily', '2026-10-22'], ['monthly', '2026-10-01'], ['weekly', '2026-10-19']]);
        assert.equal((await run({ apply: true })).inserted, 0);
        const staff = missions[0];
        await connection.execute('UPDATE portal_mission_definitions SET disabled_immediately=1 WHERE period_kind=? AND mission_id=?', [staff.period, staff.id]);
        await connection.execute('INSERT INTO portal_mission_definition_versions(period_kind,mission_id,version,effective_period_start,enabled,definition,actor_steam_id)VALUES(?,?,2,?,0,?,?)', [staff.period, staff.id, '2026-10-23', JSON.stringify({ id: staff.id, title: 'Staff edited target', metric: 'kills', target: 99, tokens: '777', rewards: [] }), '76561198000000001']);
        const [parentsBefore] = await connection.query('SELECT * FROM portal_mission_definitions ORDER BY period_kind,mission_id');
        const [versionsBefore] = await connection.query('SELECT * FROM portal_mission_definition_versions ORDER BY period_kind,mission_id,version');
        assert.equal((await run({ apply: true })).inserted, 0);
        const [parentsAfter] = await connection.query('SELECT * FROM portal_mission_definitions ORDER BY period_kind,mission_id');
        const [versionsAfter] = await connection.query('SELECT * FROM portal_mission_definition_versions ORDER BY period_kind,mission_id,version');
        assert.deepEqual(parentsAfter, parentsBefore);
        assert.deepEqual(versionsAfter, versionsBefore);
        assert.equal(backups.get('before.json').versions.length, 101);

        // This database was generated by the test; clearing it creates a fresh failure case.
        await connection.query('DELETE FROM portal_mission_definition_versions');
        await connection.query('DELETE FROM portal_mission_definitions');
        await assert.rejects(run({ apply: true, writeBackup: async () => { throw new Error('backup unavailable'); } }), /backup unavailable/);
        assert.deepEqual(await counts(), [0, 0]);
        await assert.rejects(run({ apply: true, writeBackup: async (name, data) => {
            if (name === 'verification.json') throw new Error('verification backup unavailable');
            await writeBackup(name, data);
        } }), /verification backup unavailable/);
        assert.deepEqual(await counts(), [0, 0]);
    } finally {
        if (created) await connection.query('DROP DATABASE `' + database + '`');
        await connection.end();
    }
});
